// Generates supabase/seed.sql from the app's seed recipes so the shared catalog
// matches the in-app fallback data. Run: node scripts/gen-seed-sql.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { RECIPES } from '../src/data/seed.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const j = (o) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;

const rows = RECIPES.map((r) => `(${[
  q(r.id), q(r.title), q(r.cuisine), q(r.meal), r.time, r.servings, r.cal,
  q(r.difficulty), r.rating, r.reviews, q(r.img), j(r.source), r.saves, r.cooked,
  q(r.desc), j(r.tags), j(r.nutrition), j(r.ingredients), j(r.steps), 'false', 'null',
].join(', ')})`);

const sql = `-- Seed: shared recipe catalog (generated by scripts/gen-seed-sql.mjs)
insert into public.recipes
  (id, title, cuisine, meal, time, servings, cal, difficulty, rating, reviews, img, source, saves, cooked, description, tags, nutrition, ingredients, steps, imported, owner)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync(join(__dirname, '..', 'supabase', 'seed.sql'), sql);
console.log(`Wrote supabase/seed.sql with ${RECIPES.length} recipes.`);
